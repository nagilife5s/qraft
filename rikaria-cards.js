export function cdN(u) { return CARDS[u] ? CARDS[u].c.length : 0; }
export function cdHas(ch, u, i) { var v = ch && ch.cd && ch.cd[u] && ch.cd[u][CD_KEY[Math.floor(i / CD_BITS)]] || 0; return Math.floor(v / Math.pow(2, i % CD_BITS)) % 2 === 1; }
export function cdCount(ch, u) { var n = 0; for (var i = 0; i < cdN(u); i++) if (cdHas(ch, u, i)) n++; return n; }
export function cdFull(ch, u) { return cdN(u) > 0 && cdCount(ch, u) === cdN(u); }
/* カードを1枚足す（持っていたら何もしない）。cd/<単元> は { a: 数, b: 数, c: 数 } */
export function cdAdd(ch, u, i) {
  if (!CARDS[u] || i < 0 || i >= cdN(u) || cdHas(ch, u, i)) return false;
  var k = CD_KEY[Math.floor(i / CD_BITS)]; ch.cd = Object.assign({}, ch.cd || {}); ch.cd[u] = Object.assign({}, ch.cd[u] || {});
  ch.cd[u][k] = (ch.cd[u][k] || 0) + Math.pow(2, i % CD_BITS); return true;
}
