function norm(s) { return String(s || '').replace(/[（(].*?[）)]/g, '').replace(/[\s　]/g, ''); }
/* 正解したときに落とすカードの番号（落ちなければ -1）。ans＝正解の答えの文字の配列。r＝0〜1 の乱数を返す関数（テスト用） */
export function cdRoll(ch, u, ans, r) {
  r = r || Math.random; if (!CARDS[u] || cdFull(ch, u)) return -1;
  var c = CARDS[u].c, A = (ans || []).map(norm).filter(Boolean);
  for (var i = 0; i < c.length; i++) if (!cdHas(ch, u, i) && A.indexOf(norm(c[i][0])) >= 0) return r() < CD_P.hit ? i : -1;
  if (r() >= CD_P.base) return -1;
  var left = [], tot = 0; c.forEach(function (x, j) { if (!cdHas(ch, u, j)) { left.push(j); tot += CD_P.w[x[3]] || 1; } });
  var t = r() * tot; for (var j = 0; j < left.length; j++) { t -= CD_P.w[c[left[j]][3]] || 1; if (t < 0) return left[j]; }
  return left[left.length - 1];
}
